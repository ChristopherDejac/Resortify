/* Central user bookings — power of truth for Bookings, Details & Receipt */

export const peso = (n) => "₱" + Number(n).toLocaleString("en-PH");

const receiptFields = (r) => ({
  transactionId: r.transactionId,
  paidAt: r.paidAt,
  method: r.method,
  methodLabel: r.methodLabel,
  account: r.account,
  items: r.items,
  total: r.total,
});

const booking = (b) => ({
  id: b.id,
  resortId: b.resortId,
  resort: b.resort,
  label: b.label || "DATES",
  dates: b.dates,
  checkIn: b.checkIn,
  checkOut: b.checkOut,
  stayType: b.stayType,
  guests: b.guests,
  accommodation: b.accommodation,
  location: b.location,
  status: b.status,
  statusColor: b.statusColor,
  emoji: b.emoji,
  gradient: b.gradient,
  bookingRef: b.bookingRef,
  statusSubtitle: b.statusSubtitle,
  statusNote: b.statusNote,
  address: b.address,
  rating: b.rating,
  categoryPill: b.categoryPill,
  amount: b.amount,
  amountLabel: peso(b.amount),
  itinerary: b.itinerary,
  payment: b.payment,
  receipt: receiptFields(b.receipt),
});

